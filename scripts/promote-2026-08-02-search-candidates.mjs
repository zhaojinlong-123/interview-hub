function normalize(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/[，。！？、；：“”‘’（）()[\]{}<>《》/\\\-_:,.!?;\s]/g, "")
    .replace(/visionlanguageaction/g, "vla")
    .trim();
}

function containsMatch(post, match) {
  const text = [post.title, post.content, post.sourceUrl].filter(Boolean).join(" ");
  return text.includes(match);
}

const posts = JSON.parse(await fs.readFile(POSTS_FILE, "utf8"));
const used = new Set();
for (const post of posts) {
  for (const question of post.questions || []) used.add(normalize(question));
}

const promoted = [];
for (const item of PROMOTIONS) {
  const post = posts.find((candidate) => candidate.id?.startsWith("auto-20260802-") && containsMatch(candidate, item.match));
  if (!post) continue;
  const key = normalize(item.question);
  if (used.has(key)) continue;
  post.questions = [item.question];
  post.questionAnswers = [{
    question: item.question,
    answer: item.answer,
    answerStatus: "model_answered",
    answeredAt: new Date().toISOString(),
    source: "promote-2026-08-02-search-candidates",
  }];
  post.tags = Array.from(new Set([...(post.tags || []), ...item.tags]));
  post.reviewStatus = "question_ready";
  post.difficulty = post.difficulty || "中等";
  post.updatedAt = Math.floor(Date.now() / 1000);
  used.add(key);
  promoted.push({ id: post.id, title: post.title, question: item.question });
}

